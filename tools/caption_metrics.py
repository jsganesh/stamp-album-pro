"""Write web/caption_metrics.js: the caption font's advance widths, for the editor.

The editor measures captions with the same numbers as the exports
(engines/caption_fonts.py reads them from the bundled TTFs), so a caption breaks
in the same places in every view. Rerun after changing the bundled fonts:

    python3 tools/caption_metrics.py

src/tests/test_caption_fonts.py fails if the file is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from stamp_album.engines import caption_fonts  # noqa: E402

OUT = ROOT / "src" / "stamp_album" / "web" / "caption_metrics.js"


def table() -> dict:
    out = {}
    for fid in caption_fonts.FONTS:
        upm, adv, notdef = caption_fonts.metrics(fid)
        # Runs of consecutive code points: [first, advance, advance, ...]
        runs, run = [], None
        for cp in sorted(adv):
            if run is not None and cp == run[0] + len(run) - 1:
                run.append(adv[cp])
            else:
                run = [cp, adv[cp]]
                runs.append(run)
        out[fid] = {"upm": upm, "notdef": notdef, "runs": runs}
    return out


def source() -> str:
    data = json.dumps(table(), separators=(",", ":"))
    return (
        "// Generated by tools/caption_metrics.py from web/fonts: do not edit.\n"
        "// Advance widths of Source Serif 4 Caption, per font id, as runs of\n"
        "// consecutive code points: [first code point, advance, advance, ...].\n"
        '"use strict";\n'
        "(function() {\n"
        f"var CAPTION_METRICS = {data};\n"
        "if (typeof module !== 'undefined' && module.exports) module.exports = CAPTION_METRICS;\n"
        "if (typeof window !== 'undefined') window.StampAlbumCaptionMetrics = CAPTION_METRICS;\n"
        "})();\n"
    )


if __name__ == "__main__":
    OUT.write_text(source(), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
