"""Write web/locales.js: the editor's phrase lists, from src/stamp_album/locales/*.json.

Each <lang>.json maps a key to a phrase, or to plural forms ({"one": …, "other": …}).
English (en.json) is the source; other languages translate it and may leave
phrases out, which then show in English. Keys starting with "_" are notes for
translators and are not shipped. Rerun after changing a phrase list:

    python3 tools/locales.py

src/tests/test_i18n.py fails if web/locales.js is out of date, and
tools/i18n_check.py checks the phrase lists against the editor's code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / "src" / "stamp_album" / "locales"
OUT = ROOT / "src" / "stamp_album" / "web" / "locales.js"


def load() -> dict[str, dict]:
    """Every phrase list, without the translators' notes, English first."""
    out = {}
    for path in sorted(LOCALES.glob("*.json"), key=lambda p: (p.stem != "en", p.stem)):
        data = json.loads(path.read_text(encoding="utf-8"))
        out[path.stem] = {k: v for k, v in data.items() if not k.startswith("_")}
    return out


def source() -> str:
    data = json.dumps(load(), ensure_ascii=False, indent=1, sort_keys=False)
    return (
        "// Generated by tools/locales.py from src/stamp_album/locales: do not edit.\n"
        "// The editor's phrases, per language; web/i18n.js looks them up.\n"
        '"use strict";\n'
        "(function(root) {\n"
        f"var LOCALES = {data};\n"
        "if (typeof module !== 'undefined' && module.exports) module.exports = LOCALES;\n"
        "if (root) {\n"
        "    // A list already there (a test's) is kept.\n"
        "    var have = root.StampAlbumLocales = root.StampAlbumLocales || {};\n"
        "    Object.keys(LOCALES).forEach(function(k) { if (!have[k]) have[k] = LOCALES[k]; });\n"
        "}\n"
        "})(typeof window !== 'undefined' ? window : null);\n"
    )


if __name__ == "__main__":
    OUT.write_text(source(), encoding="utf-8")
    langs = ", ".join(load())
    print(f"Wrote {OUT.relative_to(ROOT)} ({langs}; {OUT.stat().st_size // 1024} KB)")
    sys.exit(0)
